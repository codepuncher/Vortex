import { readFile } from "node:fs/promises";
import * as path from "node:path";

import {
  FileSourceKind,
  type IGeneratedFile,
  type LockfileContribution,
  type LockfileContributionCondition,
} from "@nexusmods/mod-pipeline";
import { expect, vi } from "vitest";

import type * as NexusIntegrationUtil from "../../nexus_integration/util";

// util/Steam reads paths at import time and there is no ApplicationData here
vi.mock("../../../util/getVortexPath", () => ({ default: vi.fn(() => "/tmp") }));
// the Nexus game list comes from the network
vi.mock("../../nexus_integration/util", async (importOriginal) => ({
  ...(await importOriginal<typeof NexusIntegrationUtil>()),
  nexusGames: () => [{ domain_name: "skyrimspecialedition", id: 1704 }],
}));

import { makeDeployedGame } from "../../../test-utils/deployedGame";
import { test } from "../../../test-utils/harnessTest";
import type { IState } from "../../../types/IState";
import { checksum } from "../../../util/checksum";
import { sessionReducer } from "../reducers/session";
import { contributorOf, makeLockfileContributions, resolveLockfile } from "./resolveLockFile";

const hashFile = async (filePath: string) => checksum(await readFile(filePath));
const pluginsTxt = Buffer.from("# Automatically generated by Vortex\r\n*Café.esp\r\n", "latin1");

async function makeResolvableGame() {
  const game = await makeDeployedGame({
    methodId: "hardlink_activator",
    extraReducers: [{ path: ["session", "mods"], reducer: sessionReducer }],
  });
  game.setState((draft) => {
    draft.settings.gameMode.discovered[game.gameId].store = "steam";
  });
  return game;
}

test("a contributed file joins the lockfile with its hash and content", async () => {
  const game = await makeResolvableGame();
  const destinationPath = path.join(game.dataPath, "plugins.txt");
  const contributions = makeLockfileContributions();
  contributions.register(
    "plugin-lists",
    () => true,
    () => Promise.resolve([{ destinationPath, content: pluginsTxt }]),
  );

  const lockfile = await resolveLockfile(game.api, game.gameId, contributions, hashFile);

  expect(lockfile.files).toEqual([
    {
      source: FileSourceKind.VortexGenerated,
      destinationPath: destinationPath.replaceAll("\\", "/"),
      fileHash: checksum(pluginsTxt),
      content: pluginsTxt.toString("base64"),
    },
  ]);
});

test("a contribution is asked for the game and profile being resolved", async () => {
  const game = await makeResolvableGame();
  const generate = vi.fn<LockfileContribution<IState>>(() => Promise.resolve<IGeneratedFile[]>([]));
  const condition = vi.fn<LockfileContributionCondition<IState>>(() => true);
  const contributions = makeLockfileContributions();
  contributions.register("plugin-lists", condition, generate);

  await resolveLockfile(game.api, game.gameId, contributions, hashFile);

  expect(condition).toHaveBeenCalledWith(expect.anything(), game.gameId);
  expect(generate).toHaveBeenCalledWith(expect.anything(), game.gameId, game.profileId);
});

test("a contribution is named after the extension that registered it", () => {
  expect(contributorOf("C:/extensions/plugin-lists", { name: "Plugin Lists" })).toBe(
    "Plugin Lists",
  );
});

test("a contribution from an extension without a name is named after its path", () => {
  expect(contributorOf("C:/extensions/plugin-lists", {})).toBe("C:/extensions/plugin-lists");
});
